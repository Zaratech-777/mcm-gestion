    function renderTimeline() {
      const card = document.getElementById('tlCard'), pill = document.getElementById('tlStatusPill');
      document.getElementById('dtStartDate').value = currentOT.detonacion || '';
      document.getElementById('dtEndDate').value = currentOT.limite || '';
      const startVal = currentOT.detonacion, endVal = currentOT.limite;
      if (!startVal || !endVal) { card.style.display = 'block'; pill.className = 'tl-status-pill pill-ok'; pill.textContent = '— Ingresa las fechas —'; document.getElementById('tlBarFill').style.width = '0%'; document.getElementById('tlTodayMarker').style.display = 'none'; return; }
      card.style.display = 'block';
      const start = parseDate(startVal), end = parseDate(endVal), nowR = new Date(), now = new Date(nowR.getFullYear(), nowR.getMonth(), nowR.getDate());
      const total = diffDays(start, end);
      if (total <= 0) { pill.className = 'tl-status-pill pill-danger'; pill.textContent = '⚠ Fechas inválidas'; return; }
      const elapsed = Math.max(0, diffDays(start, now)), remaining = diffDays(now, end), pct = Math.min(100, Math.max(0, (elapsed / total) * 100)), clampPct = Math.min(96, Math.max(4, pct));
      let barColor, pillClass, pillText;
      if (now > end) { barColor = '#b02020'; pillClass = 'pill-overdue'; pillText = `🔴 Vencido hace ${Math.abs(remaining)}d`; }
      else if (pct >= 80) { barColor = '#e05c3a'; pillClass = 'pill-danger'; pillText = `🔴 ${remaining}d para entrega`; }
      else if (pct >= 55) { barColor = '#f5a623'; pillClass = 'pill-warning'; pillText = `🟡 ${remaining} días restantes`; }
      else { barColor = '#1a6fd4'; pillClass = 'pill-ok'; pillText = `🟢 ${remaining} días restantes`; }
      document.getElementById('tlBarFill').style.cssText = `width:${pct}%;background:linear-gradient(90deg,var(--mcm-blue),${barColor})`;
      const marker = document.getElementById('tlTodayMarker');
      marker.style.display = 'flex'; marker.style.left = clampPct + '%';
      document.getElementById('tlLabelStart').textContent = fmtDate(start);
      document.getElementById('tlLabelEnd').textContent = fmtDate(end);
      pill.className = 'tl-status-pill ' + pillClass; pill.textContent = pillText;
      document.getElementById('bdgTotal').textContent = total;
      document.getElementById('bdgElapsed').textContent = Math.min(elapsed, total);
      if (now > end) { document.getElementById('bdgRemIcon').textContent = '🚨'; document.getElementById('bdgRemaining').textContent = Math.abs(remaining); document.getElementById('bdgRemLabel').textContent = 'Días retraso'; document.getElementById('bdgRemaining').style.color = 'var(--red)'; }
      else { document.getElementById('bdgRemIcon').textContent = '🕐'; document.getElementById('bdgRemaining').textContent = remaining; document.getElementById('bdgRemLabel').textContent = 'Días restantes'; document.getElementById('bdgRemaining').style.color = 'var(--mcm-blue)'; }
    }

