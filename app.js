    function otWfPct(ot) {
      if (!ot) return 0;
      const done = WF_FIELDS.filter(function(f) { const v = (ot[f.key] || '').toLowerCase(); return DONE_VALS.includes(v); }).length;
      return Math.round(done / WF_FIELDS.length * 100);
    }
    function otPct(id) {
      const d = otData[id];
      // If checklist tasks exist, use checklist completion
      if (d && d.tasks && d.tasks.length > 0) {
        return Math.round((d.tasks.filter(t => t.status === 'Completado').length / d.tasks.length) * 100);
      }
      // Otherwise fall back to workflow stage progress
      const ot = ots.find(function(o) { return o.id === id; });
      return ot ? otWfPct(ot) : 0;
    }

